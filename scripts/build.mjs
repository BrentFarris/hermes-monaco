import { build } from 'esbuild';
import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
export async function bundle({ development = false } = {}) {
  // Hermes also scans JavaScript with its skill-text rules. Emit ordinary
  // quoted strings through the compiler: backtick template delimiters can be
  // mistaken for the skill inline-shell DSL in otherwise inert Monaco text.
  const common = { absWorkingDir: root, bundle: true, write: false, minify: !development,
    supported: { 'template-literal': false }, format: 'esm', platform: 'browser', target: 'es2022', logLevel: 'warning' };
  const worker = async name => {
    const result = await build({ ...common, entryPoints: [name] });
    return result.outputFiles[0].text;
  };
  const [editor, json] = await Promise.all([
    worker('monaco-editor/editor/editor.worker'), worker('monaco-editor/language/json/json.worker'),
  ]);
  const result = await build({ ...common, entryPoints: ['src/plugin.tsx'], outdir: '.build/bundle',
    external: ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime'],
    loader: { '.ttf': 'dataurl' }, metafile: true,
    define: { __EDITOR_WORKER__: JSON.stringify(editor), __JSON_WORKER__: JSON.stringify(json) },
    plugins: [{ name: 'plugin-style-text', setup(api) {
      api.onLoad({ filter: /src[\\/]styles\.css$/ }, async args => ({ contents: await readFile(args.path, 'utf8'), loader: 'text' }));
    } }],
  });
  const css = result.outputFiles.filter(file => file.path.endsWith('.css')).map(file => file.text).join('\n');
  const javascript = result.outputFiles.find(file => file.path.endsWith('.js')).text;
  const code = `// Generated by npm run build. Source: src/plugin.tsx. See THIRD_PARTY_NOTICES.md.\nconst __MONACO_STYLES__=${JSON.stringify(css)};\n${javascript}`;
  const bytes = Buffer.byteLength(code);
  if (bytes > 16 * 1024 * 1024) throw new Error(`Plugin is ${bytes} bytes, exceeding Hermes's 16 MiB source limit.`);
  for (const output of Object.values(result.metafile.outputs)) {
    for (const item of output.imports) if (!(item.kind === 'url-token' && item.path.startsWith('data:')) && !['@hermes/plugin-sdk', 'react', 'react/jsx-runtime'].includes(item.path)) {
      throw new Error(`Unexpected runtime import: ${item.path.slice(0, 180)}`);
    }
  }
  await mkdir(resolve(root, 'desktop'), { recursive: true });
  await writeFile(resolve(root, 'desktop/plugin.js'), code);
  await copyFile(resolve(root, 'node_modules/monaco-editor/LICENSE'), resolve(root, 'desktop/LICENSE.monaco-editor.txt'));
  await copyFile(resolve(root, 'node_modules/marked/LICENSE.md'), resolve(root, 'desktop/LICENSE.marked.txt'));
  await copyFile(resolve(root, 'node_modules/dompurify/LICENSE'), resolve(root, 'desktop/LICENSE.dompurify.txt'));
  return { bytes, code };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { bytes } = await bundle();
  console.log(`Built desktop/plugin.js: ${(bytes / 1024 / 1024).toFixed(2)} MiB (16 MiB maximum).`);
}
